// Helper to generate packaging options
function makePkgSizes(pricePerKg: number | null, unit: string = 'per kg') {
  if (pricePerKg === null) {
    return [
      { label: '500g Pack', available: true },
      { label: '1 kg Box', available: true }
    ];
  }
  if (unit === 'per piece') {
    return [
      { label: '1 Pcs (100g)', price: pricePerKg, available: true },
      { label: '4 Pcs Pack', price: pricePerKg * 4, available: true },
      { label: '8 Pcs Family Pack', price: pricePerKg * 8, available: true }
    ];
  }
  if (unit === 'per box') {
    return [
      { label: 'Standard Box', price: pricePerKg, available: true }
    ];
  }
  const q250 = Math.round(pricePerKg * 0.25);
  const q500 = Math.round(pricePerKg * 0.5);
  return [
    { label: '250g Box', price: q250, available: true },
    { label: '500g Box', price: q500, available: true },
    { label: '1 kg Box', price: pricePerKg, available: true }
  ];
}

